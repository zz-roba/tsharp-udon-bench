#!/usr/bin/env python3
"""Generate every version of every benchmark from its body file.

A body (bodies/<Name>.body.cs) holds the class members only. The generated
versions differ in the class header alone; the members are byte-identical.

  unity/Assets/UdonBench/USharp/<Name>U.cs              UdonSharpBehaviour (Assembly-CSharp, no asmdef)
  unity/Assets/UdonBench/TSharp/<Name>T/<Name>T.cs      TsukimiBehaviour (one folder + asmdef per benchmark)
  reference/Generated/<Name>R.cs                        plain .NET, to compute the expected values

Then it runs the plain .NET reference (dotnet run -c Release in reference/), which
writes reference/expected.json, and turns that into
  unity/Assets/UdonBench/Driver/UdonBenchExpected.cs    expected checksum per benchmark

Last, it writes a .meta file with a fixed GUID next to every script, asmdef and
folder under unity/Assets/UdonBench/, so that a fresh clone imports the same way
everywhere and Unity does not leave untracked .meta files behind.

usage: python3 tools/gen.py               generate, run the reference, write the table
       python3 tools/gen.py --no-run      reuse the committed reference/expected.json
"""
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BODIES = os.path.join(ROOT, "bodies")
UNITY_ASSETS = os.path.join(ROOT, "unity", "Assets")
BENCH_DIR = os.path.join(UNITY_ASSETS, "UdonBench")
REF_DIR = os.path.join(ROOT, "reference")
EXPECTED_JSON = os.path.join(REF_DIR, "expected.json")

# Benchmarks, in the order they run.
#   steps     = Step() calls per timed run (must be one of the K that reference/Program.cs writes)
#   tolerance = absolute tolerance for a float checksum; "0f" means the checksum must match exactly
BENCHES = [
    ("Life", 30, "0f"),
    ("Fat", 100, "0f"),
    ("Fannkuch", 21, "0f"),
    # Plain .NET rounds every float operation to single precision; Mono may keep
    # intermediates wider, so the n-body energy is compared within a tolerance.
    ("NBody", 30, "1e-4f"),
    ("Bfs", 30, "0f"),
    ("Sort", 30, "0f"),
    ("GrayScott", 30, "0f"),
    ("Sobel", 10, "0f"),
    ("Sieve", 21, "0f"),
    ("Cyclic", 10, "0f"),
    ("Fir", 30, "0f"),
    ("Rgb", 30, "0f"),
    ("Noise", 10, "0f"),
    ("Ripple", 21, "0f"),
]

USHARP_HEADER = """// Generated by tools/gen.py from bodies/{name}.body.cs. Do not edit.
using UdonSharp;
using UnityEngine;

[UdonBehaviourSyncMode(BehaviourSyncMode.None)]
public class {cls} : UdonSharpBehaviour
{{
"""

TSHARP_HEADER = """// Generated by tools/gen.py from bodies/{name}.body.cs. Do not edit.
using Tsukimi;
using UnityEngine;

public partial class {cls} : TsukimiBehaviour
{{
"""

REF_HEADER = """// Generated by tools/gen.py from bodies/{name}.body.cs. Do not edit.
using UnityEngine;

public partial class {cls} : BenchRefBase
{{
"""

ASMDEF = """{{
    "name": "UdonBench_{cls}",
    "rootNamespace": "",
    "references": [
        "TsukimiCode.UdonTools.Runtime",
        "UdonSharp.Runtime",
        "VRC.Udon"
    ],
    "includePlatforms": [],
    "excludePlatforms": [],
    "allowUnsafeCode": false,
    "overrideReferences": false,
    "precompiledReferences": [],
    "autoReferenced": true,
    "defineConstraints": [],
    "versionDefines": [],
    "noEngineReferences": false
}}
"""

SHIM = """namespace System.Runtime.CompilerServices
{
    internal static class IsExternalInit
    {
    }
}
"""

EXPECTED_CS = """// Generated by tools/gen.py from reference/expected.json (the same bodies run under plain .NET). Do not edit.
public static class UdonBenchExpected
{{
    public struct Row
    {{
        public string Name; public int Steps; public string Expected; public float Tolerance;
        public Row(string name, int steps, string expected, float tolerance)
        {{ Name = name; Steps = steps; Expected = expected; Tolerance = tolerance; }}
    }}

    // In the order the benchmarks run.
    public static readonly Row[] Rows =
    {{
{rows}
    }};
}}
"""

META_SCRIPT = """fileFormatVersion: 2
guid: {guid}
MonoImporter:
  externalObjects: {{}}
  serializedVersion: 2
  defaultReferences: []
  executionOrder: 0
  icon: {{instanceID: 0}}
  userData:
  assetBundleName:
  assetBundleVariant:
"""

META_ASMDEF = """fileFormatVersion: 2
guid: {guid}
AssemblyDefinitionImporter:
  externalObjects: {{}}
  userData:
  assetBundleName:
  assetBundleVariant:
"""

META_FOLDER = """fileFormatVersion: 2
guid: {guid}
folderAsset: yes
DefaultImporter:
  externalObjects: {{}}
  userData:
  assetBundleName:
  assetBundleVariant:
"""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def generate_sources():
    for name, _, _ in BENCHES:
        with open(os.path.join(BODIES, name + ".body.cs"), encoding="utf-8") as f:
            body = f.read()
        tail = "}\n"
        write(os.path.join(BENCH_DIR, "USharp", name + "U.cs"),
              USHARP_HEADER.format(name=name, cls=name + "U") + body + tail)
        tdir = os.path.join(BENCH_DIR, "TSharp", name + "T")
        write(os.path.join(tdir, name + "T.cs"),
              TSHARP_HEADER.format(name=name, cls=name + "T") + body + tail)
        write(os.path.join(tdir, "UdonBench_" + name + "T.asmdef"), ASMDEF.format(cls=name + "T"))
        write(os.path.join(tdir, "IsExternalInit.cs"), SHIM)
        write(os.path.join(REF_DIR, "Generated", name + "R.cs"),
              REF_HEADER.format(name=name, cls=name + "R") + body + tail)


def run_reference():
    cmd = ["dotnet", "run", "-c", "Release", "--project", REF_DIR, "--", EXPECTED_JSON]
    print("running:", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=ROOT, check=True)


def write_expected_table():
    with open(EXPECTED_JSON, encoding="utf-8") as f:
        expected = json.load(f)
    rows = []
    for name, steps, tol in BENCHES:
        per_k = expected.get(name, {})
        if str(steps) not in per_k:
            sys.exit(f"reference/expected.json has no value for {name} after {steps} steps; "
                     f"add {steps} to the K list in reference/Program.cs")
        value = per_k[str(steps)]["checksum"]
        rows.append(f'        new Row("{name}", {steps}, "{value}", {tol}),')
    write(os.path.join(BENCH_DIR, "Driver", "UdonBenchExpected.cs"),
          EXPECTED_CS.format(rows="\n".join(rows)))


def guid_for(asset_path):
    # asset_path is relative to unity/, with forward slashes (e.g. Assets/UdonBench/Driver).
    return hashlib.md5(("tsharp-udon-bench:" + asset_path).encode("utf-8")).hexdigest()


def write_metas():
    count = 0

    def meta(abs_path, template):
        nonlocal count
        rel = os.path.relpath(abs_path, os.path.join(ROOT, "unity")).replace(os.sep, "/")
        write(abs_path + ".meta", template.format(guid=guid_for(rel)))
        count += 1

    meta(BENCH_DIR, META_FOLDER)
    for dirpath, dirnames, filenames in os.walk(BENCH_DIR):
        dirnames.sort()
        for d in dirnames:
            meta(os.path.join(dirpath, d), META_FOLDER)
        for fn in sorted(filenames):
            p = os.path.join(dirpath, fn)
            if fn.endswith(".cs"):
                meta(p, META_SCRIPT)
            elif fn.endswith(".asmdef"):
                meta(p, META_ASMDEF)
            # Anything else (program assets, the scene) is made by Unity and keeps Unity's own .meta.
    return count


def main():
    no_run = "--no-run" in sys.argv[1:]
    generate_sources()
    if not no_run:
        run_reference()
    write_expected_table()
    metas = write_metas()
    print(f"generated {len(BENCHES)} benchmarks, the expected table and {metas} .meta files")
    subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), "readme_bodies.py")], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
